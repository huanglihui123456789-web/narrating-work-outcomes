# 文体缺件/越界是整篇结构规则（在 validate_skill.py 里单独断言），
# 按句评测时必然全中，混进来只会淹没信号，这里过滤掉。
DOC_LEVEL = {"文体缺件", "文体越界", "超篇幅", "文体未知"}


def run_case(mode: str, text: str, style: str = "") -> list[str]:
    # final 默认按 review 文体：让 STAR-L 判断句豁免生效；自评样本单独指定
    style = style or ("review" if mode == "final" else "")
    issues = audit(text, mode, 0, style)["issues"]
    return [i["type"] for i in issues if i["type"] not in DOC_LEVEL]


import wordpack


def main() -> int:
    wordpack.use_utf8_console()
    ap = argparse.ArgumentParser(description="检查项双向评测")
    ap.add_argument("--case", default="", help="只跑编号含该关键字的样本")
    args = ap.parse_args()

    tp = fp = fn = 0
    failures = []
    for case in CASES:
        cid, mode, text, expect, note = case[:5]
        style = case[5] if len(case) > 5 else ""
        if args.case and args.case not in cid:
            continue
        fired = run_case(mode, text, style)
        missing = [e for e in expect if e not in fired]
        extra = [f for f in fired if f not in expect]
        tp += len(expect) - len(missing)
        fn += len(missing)
        fp += len(extra)
        ok = not missing and not extra
        flag = "PASS" if ok else "FAIL"
        detail = ""
        if missing:
            detail += f" 漏报{missing}"
        if extra:
            detail += f" 误报{extra}"
        print(f"{flag}  {cid:<24} {note}{detail}")
        if not ok:
            failures.append(cid)

    total = len(CASES) if not args.case else len(failures)
    prec = tp / (tp + fp) * 100 if (tp + fp) else 100.0
    rec = tp / (tp + fn) * 100 if (tp + fn) else 100.0
    print(f"\n样本 {len(CASES)} 条：期望命中 {tp}、误报 {fp}、漏报 {fn}")
    print(f"精确率 {prec:.1f}%　召回率 {rec:.1f}%")
    if failures:
        print("待修:", "、".join(failures))
        return 1
    print("双向达标。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
